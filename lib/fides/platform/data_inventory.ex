defmodule Fides.Platform.DataInventory do
  @moduledoc """
  Renders the data inventory: every attribute of every resource in the
  configured domains with its classification. The classification is the source of
  truth; the generated file is never edited by hand.
  """

  alias Fides.Platform.Classification

  @path "docs/generated/data-inventory.md"

  @spec path() :: String.t()
  def path, do: @path

  @spec render() :: String.t()
  def render do
    domains = Application.fetch_env!(:fides, :ash_domains)

    sections =
      for domain <- Enum.sort(domains),
          resource <- Enum.sort(Ash.Domain.Info.resources(domain)) do
        render_resource(resource)
      end

    Enum.join(
      [
        "# Data inventory",
        "Generated by `mix fides.gen.inventory` from the classification declared on each resource. Do not edit by hand.",
        render_summary(domains)
        | sections
      ],
      "\n\n"
    ) <> "\n"
  end

  defp render_summary(domains) do
    counts =
      for domain <- domains,
          resource <- Ash.Domain.Info.resources(domain),
          {_attribute, class} <- Classification.Info.classes(resource),
          reduce: %{} do
        counts -> Map.update(counts, class, 1, &(&1 + 1))
      end

    rows =
      for class <- Classification.Entry.classes() do
        "| #{class} | #{Map.get(counts, class, 0)} |"
      end

    Enum.join(["| Class | Attributes |", "| --- | --- |" | rows], "\n")
  end

  defp render_resource(resource) do
    classes = Classification.Info.classes(resource)

    rows =
      for attribute <- Ash.Resource.Info.attributes(resource) do
        "| `#{attribute.name}` | #{inspect(attribute.type)} | #{Map.fetch!(classes, attribute.name)} |"
      end

    Enum.join(
      [
        "## #{inspect(resource)} (`#{table(resource)}`)",
        "",
        "| Attribute | Type | Class |",
        "| --- | --- | --- |" | rows
      ],
      "\n"
    )
  end

  defp table(resource) do
    if AshPostgres.DataLayer in Spark.extensions(resource) do
      AshPostgres.DataLayer.Info.table(resource)
    else
      "no table"
    end
  end
end
